"""Double the existing STS columns, lift rigid upper works and move them seaward.

Build after build_sts_dimensions.py. Does not modify mesh data or the ground.
All deformation/placement overrides live in a separate, reversible layer.
"""
from pathlib import Path
import sys
from pxr import Gf, Sdf, Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_sts_dimensions import bounds, prepend
from sts_control import INITIAL, rope_endpoints, stay_endpoints, cylinder_matrix

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'omniverse/scenes/sts_elevation.usda'
COLUMN_FACTOR = 2.0
SEAWARD_SHIFT_M = 3.0
LEG_NAME = 'SMART_PORT_quay_sts_crane_0_orange_leg_0_data'
GROUND_TAGS = ('wheel', 'hub', 'bogie', 'axle', 'foot_gusset')


def translate(v):
    return Gf.Matrix4d(1).SetTranslate(Gf.Vec3d(v))


def apply_world_delta(prim, matrix, cache, suffix):
    parent = cache.GetLocalToWorldTransform(prim.GetParent())
    prepend(prim, parent * matrix * parent.GetInverse(), suffix)


def build():
    stage = Usd.Stage.Open(str(ROOT / 'omniverse/scenes/smart_port.usda'))
    gauge = OUTPUT.with_name('sts_track_gauge.usda')
    if gauge.exists():
        stage.MuteLayer(str(gauge))
    if OUTPUT.exists():
        stage.MuteLayer(str(OUTPUT))
    # Snapshot original transforms/classification before authoring any overrides.
    cache = UsdGeom.XformCache()
    plans = []
    for crane in stage.GetPrimAtPath('/World/STSControls').GetChildren():
        path = str(crane.GetPath())
        leg = bounds(stage, path + '/Gantry/Fixed/' + LEG_NAME)
        base, top = leg.GetMin()[2], leg.GetMax()[2]
        lift = (top - base) * (COLUMN_FACTOR - 1)
        upper_world = Gf.Vec3d(-SEAWARD_SHIFT_M, 0, lift)
        gantry = cache.GetLocalToWorldTransform(stage.GetPrimAtPath(path + '/Gantry'))
        offset = gantry.GetInverse().TransformDir(upper_world)
        fixed = []
        for child in stage.GetPrimAtPath(path + '/Gantry/Fixed').GetChildren():
            name = child.GetName().lower()
            low = bounds(stage, child.GetPath()).GetMin()[2]
            if any(tag in name for tag in GROUND_TAGS):
                kind = 'ground'
            elif low >= top - .08:
                kind = 'upper'
            else:
                kind = 'column'
            fixed.append((child, kind))
        plans.append((crane, path, base, lift, upper_world, offset, fixed))

    layer = Sdf.Layer.CreateAnonymous('sts_elevation.usda')
    layer.comment = 'Generated by build_sts_elevation.py; doubles columns, rigid upper lift and sea offset.'
    stage.GetSessionLayer().subLayerPaths.insert(0, layer.identifier)
    with Usd.EditContext(stage, layer):
        for crane, path, base, lift, upper_world, offset, fixed in plans:
            crane.CreateAttribute('sts:upperOffset', Sdf.ValueTypeNames.Double3).Set(offset)
            crane.CreateAttribute('sts:columnHeightFactor', Sdf.ValueTypeNames.Double).Set(COLUMN_FACTOR)
            crane.CreateAttribute('sts:upperLiftMeters', Sdf.ValueTypeNames.Double).Set(lift)
            crane.CreateAttribute('sts:upperSeawardMeters', Sdf.ValueTypeNames.Double).Set(SEAWARD_SHIFT_M)
            stretch = Gf.Matrix4d(1).SetScale(Gf.Vec3d(1, 1, COLUMN_FACTOR))
            stretch.SetTranslateOnly(Gf.Vec3d(0, 0, base * (1 - COLUMN_FACTOR)))
            for child, kind in fixed:
                if kind == 'ground':
                    continue
                apply_world_delta(child, translate(upper_world) if kind == 'upper' else stretch,
                                  cache, 'stsColumnLift')
            for name in ('Boom', 'Trolley'):
                prepend(stage.GetPrimAtPath(path + '/Gantry/' + name), translate(offset), 'stsUpperPlacement')
            # Keep the home spreader height/size and extend the ropes instead.
            prepend(stage.GetPrimAtPath(path + '/Gantry/Trolley/Hoist'),
                    translate(Gf.Vec3d(0, 0, -offset[2])), 'stsHoistHomeCompensation')
            width = crane.GetAttribute('sts:fixedWidthScale').Get()
            anchor = crane.GetAttribute('sts:fixedWidthAnchor').Get()
            ends = rope_endpoints(INITIAL['trolley'], INITIAL['hoist'], upper_offset=offset)
            ends += stay_endpoints(0, width, anchor, offset)
            for i, (a, b) in enumerate(ends):
                p = stage.GetPrimAtPath(path + f'/Gantry/DynamicCables/Cable_{i}')
                UsdGeom.Xformable(p).GetOrderedXformOps()[0].Set(cylinder_matrix(a, b, .012 if i < 4 else .017))
    layer.Export(str(OUTPUT))
    print(f'Built {OUTPUT.name}: {len(plans)} cranes; columns x{COLUMN_FACTOR}; '
          f'upper lift {plans[0][3]:.3f} m; sea shift {SEAWARD_SHIFT_M:g} m')


if __name__ == '__main__':
    build()
