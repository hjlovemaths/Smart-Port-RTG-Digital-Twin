"""Non-destructive 2x STS height / 3x original portal span and matching quay.

Run with pxr available. Reads the existing composed scene with this layer muted,
so rerunning never compounds the scale or replaces the customized crane asset.
"""
from pathlib import Path
import sys

from pxr import Gf, Sdf, Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sts_control import cylinder_matrix, stay_endpoints

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'omniverse/scenes/sts_dimensions.usda'
HEIGHT_FACTOR = 2.0
# Previous portal span was 2x the source; widen that result another 50%.
WIDTH_FACTOR = 2.0 * 1.5
QUAY_EXTENSION = 20.0
QUAY = '/World/SMART_PORT_OFFSHORE_QUAY'


def bounds(stage, path):
    return UsdGeom.BBoxCache(Usd.TimeCode.Default(), ['default', 'render']).ComputeWorldBound(
        stage.GetPrimAtPath(path)).ComputeAlignedRange()


def prepend(prim, matrix, suffix):
    xf = UsdGeom.Xformable(prim)
    old = xf.GetOrderedXformOps()
    op = xf.AddTransformOp(UsdGeom.XformOp.PrecisionDouble, suffix)
    op.Set(matrix)
    xf.SetXformOpOrder([op] + old)


def wheel_center(stage, crane, number):
    fixed = stage.GetPrimAtPath(crane + '/Gantry/Fixed')
    wheels = [p for p in fixed.GetChildren()
              if p.GetName().startswith(f'SMART_PORT_quay_sts_crane_0_wheel_{number}_')]
    if not wheels:
        raise ValueError(f'Missing wheel bank {number}: {crane}')
    return sum(bounds(stage, p.GetPath()).GetMidpoint()[0] for p in wheels) / len(wheels)


def shift_x(prim, dx):
    attr = prim.GetAttribute('xformOp:translate')
    v = Gf.Vec3d(attr.Get())
    v[0] += dx
    attr.Set(v)


def resize_x(prim, dx):
    attr = prim.GetAttribute('xformOp:scale')
    v = Gf.Vec3f(attr.Get())
    v[0] += dx
    attr.Set(v)


def build():
    stage = Usd.Stage.Open(str(ROOT / 'omniverse/scenes/smart_port.usda'))
    gauge = OUTPUT.with_name('sts_track_gauge.usda')
    if gauge.exists():
        stage.MuteLayer(str(gauge))
    elevation = OUTPUT.with_name('sts_elevation.usda')
    if elevation.exists():
        stage.MuteLayer(str(elevation))
    if OUTPUT.exists():
        stage.MuteLayer(str(OUTPUT))
    cranes = list(stage.GetPrimAtPath('/World/STSControls').GetChildren())
    original_deck = bounds(stage, QUAY + '/Decks/OffshoreQuayPlatform')
    landside_edge = original_deck.GetMax()[0] + QUAY_EXTENSION
    original_causeway = bounds(stage, QUAY + '/Decks/Causeway_01')
    rail_top = bounds(stage, QUAY + '/Rails/STS_Rail_01').GetMax()[2]
    baselines = []
    for crane in cranes:
        path = str(crane.GetPath())
        sea, land = wheel_center(stage, path, 0), wheel_center(stage, path, 2)
        root_x = UsdGeom.XformCache().GetLocalToWorldTransform(crane).ExtractTranslation()[0]
        baselines.append((path, sea, land, sea - root_x,
                          bounds(stage, path + '/Gantry').GetMin()[2]))
    sea, land = baselines[0][1:3]
    new_land = sea + (land - sea) * WIDTH_FACTOR
    for _, s, l, _, _ in baselines:
        if abs(s - sea) > 1e-4 or abs(l - land) > 1e-4:
            raise ValueError('The cranes do not share wheel tracks')

    layer = Sdf.Layer.CreateAnonymous('sts_dimensions.usda')
    layer.comment = 'Generated by build_sts_dimensions.py; original crane meshes retained.'
    stage.GetSessionLayer().subLayerPaths.insert(0, layer.identifier)
    with Usd.EditContext(stage, layer):
        for path, _, _, anchor, bottom in baselines:
            crane = stage.GetPrimAtPath(path)
            for name, value in (('heightFactor', HEIGHT_FACTOR),
                                ('fixedWidthScale', WIDTH_FACTOR), ('fixedWidthAnchor', anchor)):
                crane.CreateAttribute('sts:' + name, Sdf.ValueTypeNames.Double).Set(value)
            height = Gf.Matrix4d(1).SetScale(Gf.Vec3d(1, 1, HEIGHT_FACTOR))
            height.SetTranslateOnly(Gf.Vec3d(0, 0, rail_top - bottom * HEIGHT_FACTOR))
            prepend(stage.GetPrimAtPath(path + '/Gantry'), height, 'stsHeight')
            width = Gf.Matrix4d(1).SetScale(Gf.Vec3d(1, WIDTH_FACTOR, 1))
            width.SetTranslateOnly(Gf.Vec3d(0, anchor * (1 - WIDTH_FACTOR), 0))
            prepend(stage.GetPrimAtPath(path + '/Gantry/Fixed'), width, 'stsPortalWidth')
            for i, (a, b) in enumerate(stay_endpoints(0, WIDTH_FACTOR, anchor), start=4):
                cable = stage.GetPrimAtPath(path + f'/Gantry/DynamicCables/Cable_{i}')
                UsdGeom.Xformable(cable).GetOrderedXformOps()[0].Set(cylinder_matrix(a, b, .017))

        # Continuous tracks replace the old static-crane rails and sleepers.
        for p in stage.GetPrimAtPath('/World/PortAndRTG').GetChildren():
            name = p.GetName()
            if 'sts_crane' in name.lower() and any(
                    tag in name for tag in ('_sleeper_', '_rail_front', '_rail_back')):
                UsdGeom.Imageable(p).CreateVisibilityAttr().Set(UsdGeom.Tokens.invisible)
        for index, x in ((1, new_land), (2, sea)):
            prim = stage.GetPrimAtPath(QUAY + f'/Rails/STS_Rail_{index:02d}')
            shift_x(prim, x - prim.GetAttribute('xformOp:translate').Get()[0])

        deck = stage.GetPrimAtPath(QUAY + '/Decks/OffshoreQuayPlatform')
        shift_x(deck, QUAY_EXTENSION / 2)
        resize_x(deck, QUAY_EXTENSION)
        shift_x(stage.GetPrimAtPath(QUAY + '/Edges/LandsideEdge'), QUAY_EXTENSION)
        for p in stage.GetPrimAtPath(QUAY + '/Decks').GetChildren():
            if p.GetName().startswith('Causeway_'):
                shift_x(p, QUAY_EXTENSION / 2)
                resize_x(p, -QUAY_EXTENSION)
        for p in stage.GetPrimAtPath(QUAY + '/Markings').GetChildren():
            name = p.GetName()
            if name.startswith('Causeway_'):
                if name.endswith(('LeftEdge', 'RightEdge')):
                    shift_x(p, QUAY_EXTENSION / 2)
                    resize_x(p, -QUAY_EXTENSION)
                elif bounds(stage, p.GetPath()).GetMin()[0] < landside_edge:
                    UsdGeom.Imageable(p).CreateVisibilityAttr().Set(UsdGeom.Tokens.invisible)
            elif name.startswith('LandsideLane_'):
                shift_x(p, QUAY_EXTENSION - 2.0)
        # Move the landside support row under the widened platform.
        for p in stage.GetPrimAtPath(QUAY + '/Supports').GetChildren():
            if p.GetName().startswith('Platform_Row_01_'):
                shift_x(p, QUAY_EXTENSION)
        quay = stage.GetPrimAtPath(QUAY)
        quay.GetAttribute('smartPort:craneRailX').Set([new_land, sea])
        quay.GetAttribute('smartPort:causewayLengthMeters').Set(
            original_causeway.GetSize()[0] - QUAY_EXTENSION)
        quay.GetAttribute('smartPort:offshoreQuayRange').Set(
            f'X={original_deck.GetMin()[0]:g}..{landside_edge:g}; Y=-10..510; '
            f'access causeways X={landside_edge:g}..{original_causeway.GetMax()[0]:g}')
    layer.Export(str(OUTPUT))
    print(f'Built {OUTPUT.name}: {len(cranes)} cranes, height x{HEIGHT_FACTOR}, '
          f'wheel gauge {land-sea:.3f} -> {new_land-sea:.3f} m; '
          f'quay {original_deck.GetSize()[0]:g} -> {original_deck.GetSize()[0]+QUAY_EXTENSION:g} m')


if __name__ == '__main__':
    build()
