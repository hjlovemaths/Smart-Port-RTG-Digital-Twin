def segmented_green_belt_quads(x_range: tuple[float, float]) -> list[tuple]:
    x_min, x_max = x_range
    quads = []
    segment_start = LAYOUT_START_Y
    for center_y in ALL_CROSS_ROAD_CENTERS_Y:
        if center_y == TERMINAL_CROSS_ROAD_CENTER_Y:
            clear_start = center_y - YARD_CROSS_ROAD_HALF_WIDTH_M
            clear_end = LAYOUT_END_Y
        else:
            clear_start = max(
                LAYOUT_START_Y, center_y - GREEN_BELT_CAUSEWAY_CLEARANCE_M
            )
            clear_end = min(
                LAYOUT_END_Y, center_y + GREEN_BELT_CAUSEWAY_CLEARANCE_M
            )
        if clear_start > segment_start:
            quads.append(rect(x_min, segment_start, x_max, clear_start, 0.111))
        segment_start = max(segment_start, clear_end)
    if segment_start < LAYOUT_END_Y:
        quads.append(rect(x_min, segment_start, x_max, LAYOUT_END_Y, 0.111))
    return quads


def tree_quads(x_positions: tuple[float, ...]) -> tuple[list[tuple], list[tuple]]:
    trunk_quads = []
    crown_quads = []
    y = LAYOUT_START_Y + 7.0
    while y < LAYOUT_END_Y - 5.0:
        if all(
            abs(y - center_y) > GREEN_BELT_CAUSEWAY_CLEARANCE_M + 1.0
            for center_y in ALL_CROSS_ROAD_CENTERS_Y
        ):
            for x in x_positions:
                trunk_quads.extend(box_quads(x, y, 0.36, 0.36, 0.112, 2.25))
                crown_quads.extend(box_quads(x, y, 1.9, 1.9, 1.75, 4.15))
        y += 13.0
    return trunk_quads, crown_quads


def intersection_street_light_placements() -> list[tuple[str, float, float, float]]:
    """Place one parking-lot lamp at each true crossroad."""

    placements = []
    for road_index, (x_min, x_max) in enumerate(YARD_ROAD_X_RANGES, start=1):
        for cross_index, center_y in enumerate(BLOCK_APPROACH_LANE_CENTERS_Y, start=1):
            # Put the single intersection lamp exactly on the white-line
            # crossing at the road edge, rather than inside the asphalt lane.
            x = x_max
            y = center_y + YARD_CROSS_ROAD_HALF_WIDTH_M
            name = f"Road_{road_index:02d}_Cross_{cross_index:02d}"
            placements.append((name, x, y, 180.0))
    return placements


def yard_parking_light_placements() -> list[tuple[str, float, float, float]]:
    """Place the requested lamps on one long side of every yard strip."""

    placements = []
    for block in YARD_BLOCKS:
        count = YARD_LIGHT_COUNTS[block.name]
        y_min = YARD_LAYOUT_START_Y_M + block.start_m + YARD_LIGHT_MARGIN_M
        y_max = YARD_LAYOUT_START_Y_M + block.end_m - YARD_LIGHT_MARGIN_M
        step = (y_max - y_min) / (count - 1) if count > 1 else 0.0
        for side_index, x in enumerate(YARD_LIGHT_X_OFFSETS_M, start=1):
            # Every selected strip is the same white-line side of its road;
            # keep the lamp heads facing the yard consistently.
            rotate_z = 0.0
            for index in range(count):
                y = y_min + step * index
                placements.append(
                    (f"Yard_{block.name}_Side_{side_index}_Light_{index + 1:02d}", x, y, rotate_z)
                )
    return placements


def all_street_light_placements() -> list[tuple[str, float, float, float]]:
    # A yard endpoint can be the same physical point as a crossroad vertex.
    # Keep the intersection lamp (and its orientation) instead of stacking a
    # second three-head asset at the same coordinates.
    unique = []
    seen: set[tuple[float, float]] = set()
    for placement in [*intersection_street_light_placements(), *yard_parking_light_placements()]:
        _name, x, y, _rotate_z = placement
        key = (round(x, 4), round(y, 4))
        if key in seen:
            continue
        seen.add(key)
        unique.append(placement)
    return unique


