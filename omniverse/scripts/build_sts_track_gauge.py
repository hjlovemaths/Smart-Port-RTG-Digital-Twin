"""Widen the lower portal/rail gauge and center the tower platform above it.

Build after dimensions and elevation. Rigid legs/wheel banks move landside,
cross-members lengthen between their existing sea attachment and new land end.
"""
from pathlib import Path
import sys
from pxr import Gf, Sdf, Usd, UsdGeom

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_sts_dimensions import bounds, wheel_center, QUAY
from build_sts_elevation import LEG_NAME, apply_world_delta, translate
from sts_control import stay_endpoints, cylinder_matrix

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'omniverse/scenes/sts_track_gauge.usda'
GAUGE_FACTOR = 1.5
PLATFORM_NAME = 'CODEx_STS_Crane0_machinery_house_white_roof_panel_data'
TOWER_TAGS = ('machinery_house', 'main_mast', 'cable_anchor_top')


def build():
    stage = Usd.Stage.Open(str(ROOT / 'omniverse/scenes/smart_port.usda'))
    if OUTPUT.exists():
        stage.MuteLayer(str(OUTPUT))
    cache = UsdGeom.XformCache()
    plans = []
    for crane in stage.GetPrimAtPath('/World/STSControls').GetChildren():
        path = str(crane.GetPath())
        sea, land = (wheel_center(stage, path, i) for i in (0, 2))
        gauge = land - sea
        delta = gauge * (GAUGE_FACTOR - 1)
        fixed = stage.GetPrimAtPath(path + '/Gantry/Fixed')
        top = bounds(stage, str(fixed.GetPath()) + '/' + LEG_NAME).GetMax()[2]
        changes = []
        for p in fixed.GetChildren():
            b = bounds(stage, p.GetPath())
            if b.GetMin()[2] >= top - .08:
                continue  # upper deck, mast, machinery and stays stay put
            if b.GetSize()[0] > gauge * .5:
                # Keep both end joints seated, without scaling the leg thickness.
                factor = (b.GetSize()[0] + delta) / b.GetSize()[0]
                m = Gf.Matrix4d(1).SetScale(Gf.Vec3d(factor, 1, 1))
                m.SetTranslateOnly(Gf.Vec3d(b.GetMin()[0] * (1-factor), 0, 0))
                changes.append((p, m))
            elif b.GetMidpoint()[0] > (sea + land) / 2:
                changes.append((p, translate(Gf.Vec3d(delta, 0, 0))))
        # Center the small upper platform, not the full-width boom/deck.
        roof = bounds(stage, str(fixed.GetPath()) + '/' + PLATFORM_NAME)
        center_x = (sea + land + delta) / 2
        tower_world = Gf.Vec3d(center_x - roof.GetMidpoint()[0], 0, 0)
        gantry = cache.GetLocalToWorldTransform(stage.GetPrimAtPath(path + '/Gantry'))
        tower_offset = gantry.GetInverse().TransformDir(tower_world)
        for p in fixed.GetChildren():
            if any(tag in p.GetName().lower() for tag in TOWER_TAGS):
                changes.append((p, translate(tower_world)))
        plans.append((crane, sea, land, delta, changes, tower_offset, tower_world))
    _, sea, land, delta, _, _, _ = plans[0]
    deck = bounds(stage, QUAY + '/Decks/OffshoreQuayPlatform')
    if land + delta + 1 > deck.GetMax()[0]:
        raise ValueError('Widen the quay before increasing the rail gauge further')
    for _, s, l, d, _, _, _ in plans:
        if abs(s-sea) + abs(l-land) + abs(d-delta) > 1e-4:
            raise ValueError('All STS cranes must share the same wheel tracks')
    layer = Sdf.Layer.CreateAnonymous('sts_track_gauge.usda')
    layer.comment = 'Generated by build_sts_track_gauge.py; widened portal/rails and centered tower platform.'
    stage.GetSessionLayer().subLayerPaths.insert(0, layer.identifier)
    with Usd.EditContext(stage, layer):
        for crane, _, _, _, changes, tower_offset, _ in plans:
            crane.CreateAttribute('sts:trackGaugeFactor', Sdf.ValueTypeNames.Double).Set(GAUGE_FACTOR)
            crane.CreateAttribute('sts:trackGaugeMeters', Sdf.ValueTypeNames.Double).Set((land-sea)*GAUGE_FACTOR)
            crane.CreateAttribute('sts:towerOffset', Sdf.ValueTypeNames.Double3).Set(tower_offset)
            for p, matrix in changes:
                apply_world_delta(p, matrix, cache, 'stsTrackGauge')
            ends = stay_endpoints(0, crane.GetAttribute('sts:fixedWidthScale').Get(),
                                  crane.GetAttribute('sts:fixedWidthAnchor').Get(),
                                  crane.GetAttribute('sts:upperOffset').Get(), tower_offset)
            for i, (top, end) in enumerate(ends, 4):
                p = stage.GetPrimAtPath(str(crane.GetPath()) + f'/Gantry/DynamicCables/Cable_{i}')
                UsdGeom.Xformable(p).GetOrderedXformOps()[0].Set(cylinder_matrix(top, end, .017))
        rail = stage.GetPrimAtPath(QUAY + '/Rails/STS_Rail_01')
        attr = rail.GetAttribute('xformOp:translate')
        v = Gf.Vec3d(attr.Get()); v[0] = land + delta
        attr.Set(v)
        stage.GetPrimAtPath(QUAY).GetAttribute('smartPort:craneRailX').Set([land+delta, sea])
    layer.Export(str(OUTPUT))
    print(f'Built {OUTPUT.name}: {len(plans)} cranes; rail gauge {land-sea:.3f} -> '
          f'{(land-sea)*GAUGE_FACTOR:.3f} m; landside shift {delta:.3f} m; '
          f'tower platform centered by {plans[0][6][0]:.3f} m landside')


if __name__ == '__main__':
    build()
